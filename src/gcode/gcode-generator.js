/**
 * GCode Generator Module
 * 
 * Generates GRBL-compatible GCode from toolpaths
 */

/**
 * Generates GCode from toolpaths
 */
class GCodeGenerator {
  /**
   * Create a new GCode generator with configuration
   * @param {Object} config - Configuration for GCode generation
   */
  constructor(config) {
    this.config = config;
  }

  /**
   * Generate GCode from toolpaths
   * @param {Object} toolpathData - Toolpath data
   * @returns {Object} GCode output
   */
  generate(toolpathData) {
    const { toolpaths, metadata } = toolpathData;
    const commands = [];
    
    // Add header commands
    const header = this._generateHeader();
    
    // Add toolpath commands
    toolpaths.forEach(toolpath => {
      commands.push(...this._generatePathCommands(toolpath, metadata));
    });
    
    // Add footer commands
    const footer = this._generateFooter();
    
    // Calculate estimated time - simplified calculation
    const totalDistance = this._calculateTotalDistance(toolpaths);
    const estimatedTime = this._calculateEstimatedTime(totalDistance, metadata);
    
    return {
      commands,
      header,
      footer,
      estimatedTime,
      metadata: {
        originalFile: toolpathData.metadata?.originalFile || 'unknown',
        creationDate: new Date().toISOString(),
        maxDepth: metadata.maxDepth,
        minDepth: metadata.minDepth,
        toolDiameter: metadata.toolDiameter
      }
    };
  }

  /**
   * Generate GCode header
   * @returns {Array} Header commands
   */
  _generateHeader() {
    const header = [];
    
    // Only include header if configured
    if (this.config.output.includeHeader) {
      // Add comments
      header.push(`(Generated by SVG to GCode Converter)`);
      header.push(`(Date: ${new Date().toISOString()})`);
      header.push(`(Tool Diameter: ${this.config.tool.diameter}mm)`);
      header.push(`(Min Depth: ${this.config.grayscaleMapping.minDepth}mm)`);
      header.push(`(Max Depth: ${this.config.grayscaleMapping.maxDepth}mm)`);
      
      // Add initial setup commands for GRBL
      header.push('');
      header.push('G90'); // Absolute positioning
      header.push('G21'); // Set units to mm
      header.push(`F${this.config.machine.feedRates.default}`); // Set default feed rate
      header.push('M3 S1000'); // Start spindle (S parameter is RPM)
      header.push(`G0 Z${this.config.machine.safeHeight}`); // Move to safe height
      header.push('G0 X0 Y0'); // Move to starting position
      header.push('');
    }
    
    return header;
  }

  /**
   * Generate GCode footer
   * @returns {Array} Footer commands
   */
  _generateFooter() {
    const footer = [];
    
    // Only include footer if configured
    if (this.config.output.includeFooter) {
      footer.push('');
      footer.push(`G0 Z${this.config.machine.safeHeight}`); // Move to safe height
      footer.push('G0 X0 Y0'); // Return to origin
      footer.push('M5'); // Stop spindle
      footer.push('M2'); // End program
    }
    
    return footer;
  }

  /**
   * Generate GCode commands for a single toolpath
   * @param {Object} toolpath - Toolpath data
   * @param {Object} metadata - Metadata
   * @returns {Array} GCode commands
   */
  _generatePathCommands(toolpath, metadata) {
    const commands = [];
    const { points, id, depth } = toolpath;
    
    if (points.length === 0) {
      return commands;
    }
    
    // Add comment for the path
    commands.push(`(Path: ${id}, Depth: ${depth}mm)`);
    
    // Move to safe height before starting a new path
    commands.push(`G0 Z${this.config.machine.safeHeight}`);
    
    // Move to the first point (rapid move)
    const firstPoint = points[0];
    commands.push(`G0 X${this._formatCoordinate(firstPoint.x)} Y${this._formatCoordinate(firstPoint.y)}`);
    
    // Plunge to the cutting depth
    commands.push(`G1 Z${this._formatCoordinate(firstPoint.z)} F${this.config.machine.feedRates.plunge}`);
    
    // Reset to default feed rate
    commands.push(`F${this.config.machine.feedRates.default}`);
    
    // Process remaining points in the path
    for (let i = 1; i < points.length; i++) {
      const point = points[i];
      commands.push(`G1 X${this._formatCoordinate(point.x)} Y${this._formatCoordinate(point.y)} Z${this._formatCoordinate(point.z)}`);
    }
    
    // Return to safe height after path
    commands.push(`G0 Z${this.config.machine.safeHeight}`);
    
    return commands;
  }

  /**
   * Format a coordinate number to the appropriate precision
   * @param {number} coordinate - Coordinate value
   * @returns {string} Formatted coordinate
   */
  _formatCoordinate(coordinate) {
    const precision = this.config.output.precision || 3;
    return coordinate.toFixed(precision);
  }

  /**
   * Calculate the total travel distance for all toolpaths
   * @param {Array} toolpaths - Toolpath data
   * @returns {number} Total distance (mm)
   */
  _calculateTotalDistance(toolpaths) {
    let totalDistance = 0;
    
    toolpaths.forEach(toolpath => {
      const { points } = toolpath;
      
      if (points.length < 2) {
        return;
      }
      
      // Calculate distance between consecutive points
      for (let i = 1; i < points.length; i++) {
        const prevPoint = points[i - 1];
        const currentPoint = points[i];
        
        const dx = currentPoint.x - prevPoint.x;
        const dy = currentPoint.y - prevPoint.y;
        
        totalDistance += Math.sqrt(dx * dx + dy * dy);
      }
      
      // Add distance for the Z movements (up to safe height and back down)
      const safeHeight = this.config.machine.safeHeight;
      const firstPointZ = Math.abs(points[0].z);
      totalDistance += (safeHeight + firstPointZ) * 2;
    });
    
    return totalDistance;
  }

  /**
   * Calculate estimated machining time
   * @param {number} totalDistance - Total distance (mm)
   * @param {Object} metadata - Metadata with feed rates
   * @returns {number} Estimated time (seconds)
   */
  _calculateEstimatedTime(totalDistance, metadata) {
    // Convert feed rate from mm/min to mm/sec
    const feedRate = metadata.feedRate / 60;
    const plungeRate = metadata.plungeRate / 60;
    
    // Rough time calculation based on distance and feed rate
    // This is a simplification and doesn't account for acceleration/deceleration
    const movingTime = totalDistance / feedRate;
    
    // Add some overhead for transitions
    const overhead = 1.2; // 20% overhead
    
    return movingTime * overhead;
  }
}

module.exports = GCodeGenerator; 