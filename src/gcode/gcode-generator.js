/**
 * GCode Generator Module
 * 
 * Generates GRBL-compatible GCode from toolpaths
 */

// Import GCode flavor definitions
const { 
  GRBL_FLAVOR, 
  MARLIN_FLAVOR,
  MACH3_FLAVOR,
  FANUC_FLAVOR
} = require('./gcode-flavors');

/**
 * Generates GCode from toolpaths
 */
class GCodeGenerator {
  /**
   * Create a new GCode generator with configuration
   * @param {Object} config - Configuration for GCode generation
   */
  constructor(config) {
    this.config = config;
    
    // Initialize flavor based on configuration or default to GRBL
    this.flavor = this._initializeFlavor();
  }
  
  /**
   * Initialize the appropriate GCode flavor
   * @returns {Object} GCode flavor definition
   */
  _initializeFlavor() {
    const flavorName = this.config.machine.flavor || 'grbl';
    
    // Select appropriate flavor based on configuration
    switch (flavorName.toLowerCase()) {
      case 'grbl':
        return GRBL_FLAVOR;
      case 'marlin':
        return MARLIN_FLAVOR;
      case 'mach3':
        return MACH3_FLAVOR;
      case 'fanuc':
        return FANUC_FLAVOR;
      default:
        console.warn(`Unknown GCode flavor: ${flavorName}, using GRBL defaults`);
        return GRBL_FLAVOR;
    }
  }

  /**
   * Generate GCode from toolpaths
   * @param {Object} toolpathData - Toolpath data
   * @returns {Object} GCode output
   */
  generate(toolpathData) {
    const { toolpaths } = toolpathData;
    const metadata = {
      ...(toolpathData.metadata || {}),
      // Ensure we have consistent feedRates in the metadata
      feedRates: {
        default: this.config.machine.feedRates.default,
        plunge: this.config.machine.feedRates.plunge,
        rapid: this.config.machine.feedRates.rapid,
        ...(toolpathData.metadata?.feedRates || {})
      }
    };
    
    const commands = [];
    
    // Add header commands
    const header = this._generateHeader();
    
    // Add toolpath commands
    toolpaths.forEach((toolpath, index) => {
      // For the first path or when safety transitions are enabled, add proper transitions
      const isFirstPath = index === 0;
      const previousPath = isFirstPath ? null : toolpaths[index - 1];
      
      commands.push(...this._generatePathCommands(toolpath, metadata, previousPath));
    });
    
    // Add footer commands
    const footer = this._generateFooter();
    
    // Calculate estimated time - simplified calculation
    const totalDistance = this._calculateTotalDistance(toolpaths);
    const estimatedTime = this._calculateEstimatedTime(totalDistance, metadata);
    
    return {
      commands,
      header,
      footer,
      estimatedTime,
      metadata: {
        originalFile: toolpathData.metadata?.originalFile || 'unknown',
        creationDate: new Date().toISOString(),
        maxDepth: metadata.maxDepth,
        minDepth: metadata.minDepth,
        toolDiameter: metadata.toolDiameter,
        feedRates: metadata.feedRates,
        flavor: this.flavor.name
      }
    };
  }

  /**
   * Generate GCode header
   * @returns {Array} Header commands
   */
  _generateHeader() {
    const header = [];
    
    // Only include header if configured
    if (this.config.output.includeHeader) {
      // Add comments using the flavor's comment syntax
      const { commentStart, commentEnd } = this.flavor.syntax;
      
      header.push(`${commentStart}Generated by SVG to GCode Converter${commentEnd}`);
      header.push(`${commentStart}Date: ${new Date().toISOString()}${commentEnd}`);
      header.push(`${commentStart}Tool Diameter: ${this.config.tool.diameter}mm${commentEnd}`);
      header.push(`${commentStart}Min Depth: ${this.config.grayscaleMapping.minDepth}mm${commentEnd}`);
      header.push(`${commentStart}Max Depth: ${this.config.grayscaleMapping.maxDepth}mm${commentEnd}`);
      header.push(`${commentStart}Flavor: ${this.flavor.name}${commentEnd}`);
      
      // Add initial setup commands based on the flavor
      header.push('');
      
      // Add units command
      header.push(this.flavor.commands.useMillimeters);
      
      // Add absolute coordinates command
      header.push(this.flavor.commands.absolutePositioning);
      
      // Add feed rate command
      header.push(`F${this.config.machine.feedRates.default}`);
      
      // Add spindle start command if appropriate
      if (this.flavor.commands.startSpindle) {
        const spindleSpeed = this.config.tool.spindleSpeed || 1000;
        header.push(`${this.flavor.commands.startSpindle} S${spindleSpeed}`);
      }
      
      // Move to safe height
      header.push(`G0 Z${this.config.machine.safeHeight}`);
      
      // Move to starting position
      header.push('G0 X0 Y0');
      
      header.push('');
    }
    
    return header;
  }

  /**
   * Generate GCode footer
   * @returns {Array} Footer commands
   */
  _generateFooter() {
    const footer = [];
    
    // Only include footer if configured
    if (this.config.output.includeFooter) {
      footer.push('');
      
      // Move to safe height
      footer.push(`G0 Z${this.config.machine.safeHeight}`);
      
      // Return to origin
      footer.push('G0 X0 Y0');
      
      // Add spindle stop command if appropriate
      if (this.flavor.commands.stopSpindle) {
        footer.push(this.flavor.commands.stopSpindle);
      }
      
      // Add program end command
      footer.push(this.flavor.commands.programEnd);
    }
    
    return footer;
  }

  /**
   * Generate GCode commands for a single toolpath
   * @param {Object} toolpath - Toolpath data
   * @param {Object} metadata - Metadata
   * @param {Object} previousPath - Previous toolpath for optimal transitions
   * @returns {Array} GCode commands
   */
  _generatePathCommands(toolpath, metadata, previousPath) {
    const commands = [];
    const { points, id, depth, type, originalPath } = toolpath;
    
    if (!points || points.length === 0) {
      return commands;
    }
    
    // Add comment for the path using the flavor's comment syntax
    const { commentStart, commentEnd } = this.flavor.syntax;
    const pathId = id || `path_${Math.random().toString(36).substring(2, 10)}`;
    commands.push(`${commentStart}Path: ${pathId}, Depth: ${depth}mm${commentEnd}`);
    
    // Get safe height for transitions
    const safeHeight = this.config.machine.safeHeight || 5;
    
    // Calculate clearance height based on configuration
    const clearanceHeight = this._calculateClearanceHeight(depth);
    
    // Determine if we need a full retraction to safe height or just a clearance move
    const needsFullRetraction = this._needsFullRetraction(toolpath, previousPath);
    
    // Use the appropriate rapid move command based on flavor
    const rapidCommand = this.flavor.commands.rapidMove || 'G0';
    
    if (needsFullRetraction) {
      // Full retraction needed - go to safe height
      commands.push(`${rapidCommand} Z${this._formatCoordinate(safeHeight)}`);
    } else if (previousPath) {
      // Partial retraction to clearance height only needed if not the first path
      commands.push(`${rapidCommand} Z${this._formatCoordinate(clearanceHeight)}`);
    }
    
    // Move to the first point (rapid move)
    if (points.length > 0) {
      const firstPoint = points[0];
      commands.push(`${rapidCommand} X${this._formatCoordinate(firstPoint.x)} Y${this._formatCoordinate(firstPoint.y)}`);
      
      // Use the appropriate linear move command based on flavor
      const linearCommand = this.flavor.commands.linearMove || 'G1';
      
      // Plunge to the cutting depth with controlled feed rate
      const zDepth = firstPoint.z !== undefined ? firstPoint.z : -depth;
      commands.push(`${linearCommand} Z${this._formatCoordinate(zDepth)} F${this.config.machine.feedRates.plunge}`);
      
      // Reset to default feed rate for XY movement
      commands.push(`F${this.config.machine.feedRates.default}`);
      
      // Process remaining points in the path
      for (let i = 1; i < points.length; i++) {
        const point = points[i];
        
        // Check if we need to apply constant Z or variable Z
        if (this.config.toolpath?.constantZ) {
          // Constant Z mode - all XY moves at the same Z depth
          commands.push(`${linearCommand} X${this._formatCoordinate(point.x)} Y${this._formatCoordinate(point.y)}`);
        } else {
          // Variable Z mode - Z changes with each move
          const pointZ = point.z !== undefined ? point.z : -depth;
          commands.push(`${linearCommand} X${this._formatCoordinate(point.x)} Y${this._formatCoordinate(point.y)} Z${this._formatCoordinate(pointZ)}`);
        }
      }
      
      // Check if this is a shape that should be closed (circle, rect, or path with Z command)
      const isClosedShape = 
        type === 'circle' || 
        type === 'rect' || 
        type === 'ellipse' || 
        (originalPath && (originalPath.includes('Z') || originalPath.includes('z')));
      
      // For closed shapes, ensure we return to the starting point if we're not already there
      if (isClosedShape && points.length > 1) {
        const firstPathPoint = points[0];
        const lastPoint = points[points.length - 1];
        
        // Check if we're not already at the start point (with small tolerance)
        const distanceToStart = Math.sqrt(
          Math.pow(lastPoint.x - firstPathPoint.x, 2) + 
          Math.pow(lastPoint.y - firstPathPoint.y, 2)
        );
        
        // If we're not already at the start point, move there to close the shape
        if (distanceToStart > 0.01) {
          const pointZ = firstPathPoint.z !== undefined ? firstPathPoint.z : -depth;
          commands.push(`${linearCommand} X${this._formatCoordinate(firstPathPoint.x)} Y${this._formatCoordinate(firstPathPoint.y)} Z${this._formatCoordinate(pointZ)}`);
        }
      }
      
      // Return to Z0 before moving to clearance height
      commands.push(`${linearCommand} Z0 F${this.config.machine.feedRates.plunge}`);
    }
    
    // Return to clearance or safe height after path
    // (Full retraction will be handled before the next path starts if needed)
    commands.push(`${rapidCommand} Z${this._formatCoordinate(clearanceHeight)}`);
    
    return commands;
  }
  
  /**
   * Calculate appropriate clearance height for a given depth
   * @param {number} depth - Current cutting depth
   * @returns {number} Appropriate clearance height
   */
  _calculateClearanceHeight(depth) {
    // Base clearance height is a percentage above the current depth
    const safeHeight = this.config.machine.safeHeight;
    const minClearance = 2; // Minimum 2mm clearance
    
    // For very shallow cuts, use a smaller clearance
    // For deeper cuts, use a larger clearance
    const clearance = Math.max(minClearance, Math.abs(depth) * 0.5);
    
    // The clearance height is the negative depth (positive Z) plus the clearance amount
    // But never higher than the safe height
    return Math.min(Math.abs(depth) + clearance, safeHeight);
  }
  
  /**
   * Determine if a full retraction to safe height is needed
   * @param {Object} currentPath - Current toolpath
   * @param {Object} previousPath - Previous toolpath
   * @returns {boolean} True if full retraction is needed
   */
  _needsFullRetraction(currentPath, previousPath) {
    // Always do full retraction for the first path
    if (!previousPath) {
      return true;
    }
    
    // Safely check if points arrays exist and have elements
    if (!currentPath.points || !currentPath.points.length || 
        !previousPath.points || !previousPath.points.length) {
      // If any path doesn't have valid points, do full retraction to be safe
      return true;
    }
    
    // Get the first point of current path and last point of previous path
    const currentFirst = currentPath.points[0];
    const previousLast = previousPath.points[previousPath.points.length - 1];
    
    // Safety check for point coordinates
    if (!currentFirst || !previousLast || 
        currentFirst.x === undefined || currentFirst.y === undefined ||
        previousLast.x === undefined || previousLast.y === undefined) {
      return true;
    }
    
    // Calculate distance between the points
    const distance = Math.sqrt(
      Math.pow(currentFirst.x - previousLast.x, 2) +
      Math.pow(currentFirst.y - previousLast.y, 2)
    );
    
    // If paths are far apart, do a full retraction
    const maxDistanceForClearanceMove = this.config.machine.clearanceMoveMaxDistance || 50;
    if (distance > maxDistanceForClearanceMove) {
      return true;
    }
    
    // If depth difference is significant, do a full retraction
    const depthDifference = Math.abs(currentPath.depth - previousPath.depth);
    const maxDepthDiffForClearanceMove = this.config.machine.clearanceMoveMaxDepthDiff || 5;
    if (depthDifference > maxDepthDiffForClearanceMove) {
      return true;
    }
    
    // Default to clearance move (no full retraction needed)
    return false;
  }

  /**
   * Format a coordinate number to the appropriate precision
   * @param {number} coordinate - Coordinate value
   * @returns {string} Formatted coordinate
   */
  _formatCoordinate(coordinate) {
    const precision = this.config.output.precision || 3;
    return coordinate.toFixed(precision);
  }

  /**
   * Calculate the total travel distance for all toolpaths
   * @param {Array} toolpaths - Toolpath data
   * @returns {number} Total distance (mm)
   */
  _calculateTotalDistance(toolpaths) {
    let totalDistance = 0;
    let lastPosition = null;
    const safeHeight = this.config.machine.safeHeight || 5;
    
    // Safety check for toolpaths
    if (!toolpaths || !Array.isArray(toolpaths)) {
      return 0;
    }
    
    toolpaths.forEach((toolpath, index) => {
      // Safety check for toolpath and points
      if (!toolpath || !toolpath.points || !Array.isArray(toolpath.points) || toolpath.points.length < 1) {
        return;
      }
      
      const { points } = toolpath;
      
      // Safety check for first point
      if (!points[0] || points[0].z === undefined) {
        return;
      }
      
      // Add Z movement to/from safe height at the start of the path
      const firstPointZ = Math.abs(points[0].z || 0);
      
      // If first path or the paths are far apart, add full Z retraction
      if (index === 0 || !lastPosition) {
        // Initial retraction from Z=0 to safe height
        totalDistance += safeHeight;
      } else {
        // Calculate clearance height for previous path
        const previousDepth = toolpaths[index - 1]?.depth || 0;
        const clearanceHeight = this._calculateClearanceHeight(previousDepth);
        
        // Add distance for partial Z retraction
        totalDistance += clearanceHeight - (lastPosition.z || 0);
        
        // Calculate XY travel distance to new path
        const dx = (points[0].x || 0) - (lastPosition.x || 0);
        const dy = (points[0].y || 0) - (lastPosition.y || 0);
        totalDistance += Math.sqrt(dx * dx + dy * dy);
      }
      
      // Add plunge distance from safe/clearance height to first point
      totalDistance += safeHeight - firstPointZ;
      
      // Calculate XY path distance between points
      for (let i = 1; i < points.length; i++) {
        const prevPoint = points[i - 1];
        const currentPoint = points[i];
        
        // Safety check for points
        if (!prevPoint || !currentPoint) continue;
        
        const dx = (currentPoint.x || 0) - (prevPoint.x || 0);
        const dy = (currentPoint.y || 0) - (prevPoint.y || 0);
        const dz = (currentPoint.z || 0) - (prevPoint.z || 0);
        
        // Calculate 3D distance with Z component
        totalDistance += Math.sqrt(dx * dx + dy * dy + dz * dz);
      }
      
      // Save the last position for the next path
      const lastPoint = points[points.length - 1];
      if (lastPoint) {
        lastPosition = {
          x: lastPoint.x || 0,
          y: lastPoint.y || 0,
          z: lastPoint.z || 0
        };
      }
    });
    
    // Add final retraction to safe height and return to origin
    if (lastPosition) {
      // Final Z movement
      totalDistance += safeHeight - (lastPosition.z || 0);
      
      // Return to origin
      totalDistance += Math.sqrt((lastPosition.x || 0) * (lastPosition.x || 0) + (lastPosition.y || 0) * (lastPosition.y || 0));
    }
    
    return totalDistance;
  }

  /**
   * Calculate estimated machining time
   * @param {number} totalDistance - Total distance (mm)
   * @param {Object} metadata - Metadata with feed rates
   * @returns {number} Estimated time (seconds)
   */
  _calculateEstimatedTime(totalDistance, metadata) {
    // Convert feed rates from mm/min to mm/sec
    // First check if feedRates exist directly in metadata, fallback to metadata.feedRate for compatibility,
    // and finally fallback to config's feedRates
    const feedRate = (metadata.feedRates?.default || 
                     metadata.feedRate || 
                     this.config.machine.feedRates.default || 1000) / 60;
    
    const plungeRate = (metadata.feedRates?.plunge || 
                        metadata.plungeRate || 
                        this.config.machine.feedRates.plunge || 500) / 60;
    
    const rapidRate = (metadata.feedRates?.rapid || 
                       metadata.rapidRate || 
                       this.config.machine.feedRates.rapid || 3000) / 60;
    
    // Estimate Z distance (approximately 20% of total for typical engraving)
    const zDistance = totalDistance * 0.2;
    const xyDistance = totalDistance * 0.8;
    
    // Calculate time components
    const xyTime = xyDistance / feedRate;
    const zTime = zDistance / plungeRate;
    const rapidTime = (xyDistance * 0.1) / rapidRate; // Assume 10% of movement is rapid
    
    // Add some overhead for acceleration/deceleration and tool changes
    const overhead = 1.2; // 20% overhead
    
    return (xyTime + zTime + rapidTime) * overhead;
  }
}

module.exports = GCodeGenerator; 